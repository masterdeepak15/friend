// Embeds helper/helper.ps1 in src/helperScript.gen.ts so the agent is one file (agent.js) with the helper inside it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ps1 = readFileSync(join(root, "helper", "helper.ps1"), "utf8").replace(/\r\n/g, "\n");
const out = `// Generated by scripts/gen-helper.mjs from helper/helper.ps1. Do not edit.\nexport const HELPER_PS1 = ${JSON.stringify(ps1)};\n`;
const target = join(root, "src", "helperScript.gen.ts");
let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {
  /* first run */
}
if (current !== out) writeFileSync(target, out);
console.log(current === out ? "helper script is up to date" : "helper script written");
